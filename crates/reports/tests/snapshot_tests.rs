use autocompare_reports::{
    ChildReportAnchor, DiffStats, HtmlColorBuilder, HtmlMonoBuilder, HtmlReportBuilder, HtmlTheme,
    Hunk, HunkLine, PatchReportBuilder, ReportInput, TextReportBuilder, XmlReportBuilder,
    render_context_patch, render_html, render_html_color, render_html_mono,
    render_html_with_children, render_patch, render_text, render_text_with_children, render_xml,
    render_xml_with_children,
};

fn make_fixture() -> (ReportInput, Vec<ChildReportAnchor>) {
    let hunks = vec![Hunk::new(
        1,
        5,
        1,
        6,
        vec![
            HunkLine::unchanged("fn main() {", 1, 1),
            HunkLine::delete("    println!(\"Hello, old world!\");", 2),
            HunkLine::insert("    println!(\"Hello, new world!\");", 2),
            HunkLine::modify("    let version = \"1.0.0\";", 3, 3),
            HunkLine::unchanged("}", 4, 4),
        ],
    )];

    let stats = DiffStats::new(1, 1, 1, 2);
    let input = ReportInput::new("src/main.rs", hunks, stats);
    let children = vec![
        ChildReportAnchor::new("Submodule Diff", "submodule/report.html"),
        ChildReportAnchor::new("Config Diff", "config/report.html"),
    ];

    (input, children)
}

#[test]
fn test_html_color_snapshot() {
    let (input, children) = make_fixture();

    let out1 = HtmlReportBuilder::color(&input)
        .with_child_anchors(children.clone())
        .with_subtitle("Integration Test Fixture")
        .render();

    let out2 = HtmlColorBuilder::new(&input)
        .with_child_anchors(children.clone())
        .with_subtitle("Integration Test Fixture")
        .render();

    assert_eq!(out1, out2);

    assert!(out1.contains("<!DOCTYPE html>"));
    assert!(out1.contains("<title>src/main.rs - Diff Report</title>"));
    assert!(out1.contains("<h1 class=\"report-title\">src/main.rs</h1>"));
    assert!(out1.contains("<p class=\"report-subtitle\">Integration Test Fixture</p>"));
    assert!(out1.contains("+1 additions"));
    assert!(out1.contains("-1 deletions"));
    assert!(out1.contains("~1 modifications"));
    assert!(out1.contains("=2 unchanged"));
    assert!(out1.contains("<nav class=\"child-reports\" id=\"child-reports\">"));
    assert!(out1.contains("Linked Child Reports"));
    assert!(out1.contains(
        "<a class=\"child-report-anchor\" href=\"submodule/report.html\">Submodule Diff</a>"
    ));
    assert!(
        out1.contains(
            "<a class=\"child-report-anchor\" href=\"config/report.html\">Config Diff</a>"
        )
    );
    assert!(out1.contains("@@ -1,5 +1,6 @@"));
    assert!(out1.contains("diff-line line-unchanged"));
    assert!(out1.contains("diff-line line-delete"));
    assert!(out1.contains("diff-line line-insert"));
    assert!(out1.contains("diff-line line-modify"));
    assert!(out1.contains("Hello, old world!"));
    assert!(out1.contains("Hello, new world!"));
    assert!(out1.contains("let version = &quot;1.0.0&quot;;"));
    assert!(out1.contains("Generated by autocompare-reports"));

    let conv = render_html_color(&input);
    assert!(conv.contains("src/main.rs"));

    let conv_kids = render_html_with_children(&input, HtmlTheme::Color, &children);
    assert!(conv_kids.contains("Submodule Diff"));
}

