    let xml = render_xml(&input);
    let _ = std::fs::write(dir.join("sample_xml_report.xml"), xml);

    // 8. Patch
    let patch = render_patch(&input);
    let _ = std::fs::write(dir.join("sample_unified.patch"), patch);
