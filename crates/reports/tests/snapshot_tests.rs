fn make_fixture() -> (ReportInput, Vec<ChildReportAnchor>) {
    let hunks = vec![Hunk::new(
        1,
        5,
        1,
        6,
        vec![
            HunkLine::unchanged("fn main() {", 1, 1),
            HunkLine::delete("    println!(\"Hello, old world!\");", 2),
            HunkLine::insert("    println!(\"Hello, new world!\");", 2),
            HunkLine::modify("    let version = \"1.0.0\";", 3, 3),
            HunkLine::unchanged("}", 4, 4),
        ],
    )];

    let stats = DiffStats::new(1, 1, 1, 2);
    let input = ReportInput::new("src/main.rs", hunks, stats);
    let children = vec![
        ChildReportAnchor::new("Submodule Diff", "submodule/report.html"),
        ChildReportAnchor::new("Config Diff", "config/report.html"),
    ];

    (input, children)
}

