#[test]
fn test_xml_snapshot() {
    let (input, children) = make_fixture();

    let out = XmlReportBuilder::new(&input)
        .with_child_anchors(children.clone())
        .with_subtitle("XML Test Fixture")
        .render();

    assert!(out.contains("<?xml version=\"1.0\" encoding=\"UTF-8\"?>"));
    assert!(out.contains("<diff-report xmlns=\"urn:autocompare:report:v1\">"));
    assert!(out.contains("<title>src/main.rs</title>"));
    assert!(out.contains("<subtitle>XML Test Fixture</subtitle>"));
    assert!(out.contains("<stats additions=\"1\" deletions=\"1\" modifications=\"1\" unchanged=\"2\" total-changes=\"3\" />"));
    assert!(out.contains("<child-reports>"));
    assert!(
        out.contains("<child-report href=\"submodule/report.html\">Submodule Diff</child-report>")
    );
    assert!(out.contains("<child-report href=\"config/report.html\">Config Diff</child-report>"));
    assert!(out.contains("<hunk old-start=\"1\" old-lines=\"5\" new-start=\"1\" new-lines=\"6\" header=\"@@ -1,5 +1,6 @@\">"));
    assert!(
        out.contains("<line change=\"unchanged\" old-line=\"1\" new-line=\"1\">fn main() {</line>")
    );
    assert!(out.contains(
        "<line change=\"delete\" old-line=\"2\">    println!(&quot;Hello, old world!&quot;);</line>"
    ));
    assert!(out.contains(
        "<line change=\"insert\" new-line=\"2\">    println!(&quot;Hello, new world!&quot;);</line>"
    ));
    assert!(out.contains("<line change=\"modify\" old-line=\"3\" new-line=\"3\">    let version = &quot;1.0.0&quot;;</line>"));
    assert!(out.contains("</diff-report>"));

    let conv = render_xml(&input);
    assert!(conv.contains("<title>src/main.rs</title>"));

    let conv_kids = render_xml_with_children(&input, &children);
    assert!(conv_kids.contains("Submodule Diff"));
}

#[test]
fn test_unified_patch_snapshot() {
    let (input, _) = make_fixture();

    let out1 = PatchReportBuilder::new(&input)
        .with_paths("old/src/main.rs", "new/src/main.rs")
        .unified()
        .render();

    assert!(out1.contains("--- a/old/src/main.rs\n"));
    assert!(out1.contains("+++ b/new/src/main.rs\n"));
    assert!(out1.contains("@@ -1,5 +1,6 @@\n"));
    assert!(out1.contains(" fn main() {\n"));
    assert!(out1.contains("-    println!(\"Hello, old world!\");\n"));
    assert!(out1.contains("+    println!(\"Hello, new world!\");\n"));
    assert!(out1.contains("!    let version = \"1.0.0\";\n"));
    assert!(out1.contains(" }\n"));

    let out_default = render_patch(&input);
    assert!(out_default.contains("--- a/src/main.rs\n"));
    assert!(out_default.contains("+++ b/src/main.rs\n"));
    assert!(out_default.contains("@@ -1,5 +1,6 @@\n"));
}

