#[test]
fn test_hostile_input_escaping_never_panics() {
    let hostile_title = "<script>alert(\"XSS & attack 'quoted'\");</script>";
    let hostile_lines = vec![
        HunkLine::unchanged("<xml tag=\"test & <value>\">", 1, 1),
        HunkLine::delete("<b>bold & unclosed", 2),
        HunkLine::insert("'><script src=\"https://evil.com/payload.js\"></script>", 2),
        HunkLine::modify("special chars: & < > \" ' ` $ % # @ !", 3, 3),
    ];
    let hunks = vec![Hunk::new(1, 3, 1, 3, hostile_lines)];
    let stats = DiffStats::new(1, 1, 1, 1);
    let input = ReportInput::new(hostile_title, hunks, stats);

    let hostile_children = vec![ChildReportAnchor::new(
        "<child>&\"'<script>",
        "javascript:alert('evil')&foo=bar<1>",
    )];

    // 1. HTML Color & Mono
    let html_color = HtmlReportBuilder::color(&input)
        .with_child_anchors(hostile_children.clone())
        .with_parent_anchor("parent<script>", "parent.html?a=1&b=2")
        .render();
    assert!(!html_color.contains("<script>alert"));
    assert!(html_color.contains(
        "&lt;script&gt;alert(&quot;XSS &amp; attack &#39;quoted&#39;&quot;);&lt;/script&gt;"
    ));
    assert!(html_color.contains("&amp;&quot;&#39;&lt;script&gt;"));
    assert!(html_color.contains("parent&lt;script&gt;"));

    let html_mono = HtmlReportBuilder::mono(&input)
        .with_child_anchors(hostile_children.clone())
        .side_by_side()
        .render();
    assert!(!html_mono.contains("<script>alert"));
    assert!(html_mono.contains("&lt;script&gt;"));

    // 2. XML
    let xml = XmlReportBuilder::new(&input)
        .with_child_anchors(hostile_children)
        .render();
    assert!(!xml.contains("<script>alert"));
    assert!(xml.contains(
        "&lt;script&gt;alert(&quot;XSS &amp; attack &apos;quoted&apos;&quot;);&lt;/script&gt;"
    ));
    assert!(xml.contains("&lt;xml tag=&quot;test &amp; &lt;value&gt;&quot;&gt;"));

    // 3. Plain text - does not panic
    let txt = render_text(&input);
    assert!(txt.contains("<script>alert"));

    // 4. Patch - does not panic
    let patch = render_patch(&input);
    assert!(patch.contains("special chars"));
}

